-- 0021_cadastro_wpp — replica a tabela de cadastro/trava do n8n dentro
--   do nosso projeto, com a MESMA estrutura e nome, para o n8n fazer o
--   cadastro + controle de trava aqui (como já é feito hoje). Substitui
--   a ponte parcial whatsapp_travas.
--   O app lê a trava por fn_trava_status(phone) e grava por fn_set_trava,
--   escondendo o nome "feio" da tabela do PostgREST.
-- =============================================================

drop table if exists whatsapp_travas;

create table if not exists "CADASTRO N8N | NOVA AÇÃO" (
  id            bigint primary key generated by default as identity,
  created_at    timestamptz not null default now(),
  name          text,
  phone         text,
  trava         boolean not null default false,
  chatlid       text,
  "intervenção" boolean not null default false
);
alter table "CADASTRO N8N | NOVA AÇÃO" enable row level security;
create index if not exists idx_cadastro_phone on "CADASTRO N8N | NOVA AÇÃO" (phone, created_at desc);

-- estado atual da trava por telefone (última linha vence)
create or replace view v_trava_atual as
  select distinct on (phone) phone, (trava or "intervenção") as travado
  from "CADASTRO N8N | NOVA AÇÃO"
  where phone is not null
  order by phone, created_at desc;

-- está travado? (usado pelo /inbound para não acionar a Naia)
create or replace function fn_trava_status(p_phone text)
returns boolean language sql stable as $$
  select coalesce((select travado from v_trava_atual where phone = p_phone), false);
$$;

-- grava a trava (append, igual ao modelo do n8n): usado quando o Rodrigues
-- assume/responde ou devolve pra Naia
create or replace function fn_set_trava(p_phone text, p_name text, p_travado boolean)
returns void language sql as $$
  insert into "CADASTRO N8N | NOVA AÇÃO" (phone, name, trava) values (p_phone, p_name, p_travado);
$$;
